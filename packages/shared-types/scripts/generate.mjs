#!/usr/bin/env node
/**
 * Lighthouse shared-types code generator.
 *
 * Reads schema/contracts.json (the single source of truth) and emits:
 *   - ts/index.ts                               (TypeScript: union types, const arrays, metadata, interfaces)
 *   - python/lighthouse_shared/__init__.py      (Python: str Enums, metadata dicts, TypedDicts)
 *
 * Deliberately dependency-free (only Node's `fs`/`path`/`url`) so it runs in any
 * Docker stage or CI without an install step. Run: `node scripts/generate.mjs`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const contracts = JSON.parse(readFileSync(resolve(root, "schema/contracts.json"), "utf8"));

const BANNER_TS = `/* eslint-disable */
// ============================================================================
// AUTO-GENERATED by packages/shared-types/scripts/generate.mjs — DO NOT EDIT.
// Source of truth: packages/shared-types/schema/contracts.json (v${contracts.version})
// ============================================================================
`;
const BANNER_PY = `# ruff: noqa
# ============================================================================
# AUTO-GENERATED by packages/shared-types/scripts/generate.mjs — DO NOT EDIT.
# Source of truth: packages/shared-types/schema/contracts.json (v${contracts.version})
# ============================================================================
`;

// ---- helpers ---------------------------------------------------------------
const pyMemberName = (v) => v.toUpperCase().replace(/[^A-Z0-9]+/g, "_");
// "EntityType" -> "ENTITY_TYPE" (insert separators at boundaries BEFORE uppercasing).
const screamingSnake = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
// "JobStatus" -> "JOB_STATUSES", "EntityType" -> "ENTITY_TYPES" (English plural for the const array).
const pluralConst = (name) => {
  const s = screamingSnake(name);
  return s.endsWith("S") ? `${s}ES` : `${s}S`;
};
const tsType = (t) => {
  // Map our compact type DSL to TypeScript.
  if (t === "Json") return "Record<string, unknown>";
  if (t.endsWith("[]")) return `${tsType(t.slice(0, -2))}[]`;
  if (["string", "number", "boolean"].includes(t)) return t;
  return t; // enum/interface name passes through
};
const pyType = (t, optional) => {
  let base;
  if (t === "Json") base = "Dict[str, Any]";
  else if (t.endsWith("[]")) base = `List[${pyType(t.slice(0, -2), false)}]`;
  else if (t === "string") base = "str";
  else if (t === "number") base = "float";
  else if (t === "boolean") base = "bool";
  else base = t; // enum name
  return optional ? `NotRequired[${base}]` : base;
};

// ---- TypeScript ------------------------------------------------------------
function buildTs() {
  const out = [BANNER_TS, ""];

  for (const [name, def] of Object.entries(contracts.enums)) {
    const values = def.members.map((m) => m.value);
    out.push(`/** ${def.doc} */`);
    out.push(`export type ${name} = ${values.map((v) => JSON.stringify(v)).join(" | ")};`);
    out.push(`export const ${pluralConst(name)} = [${values.map((v) => JSON.stringify(v)).join(", ")}] as const;`);
    out.push("");
  }

  // Rich metadata for EntityType.
  out.push(`export interface EntityMeta { value: EntityType; label: string; color: string; icon: string; mono: boolean; }`);
  out.push(`export const ENTITY_META: Record<EntityType, EntityMeta> = {`);
  for (const m of contracts.enums.EntityType.members) {
    out.push(`  ${m.value}: { value: ${JSON.stringify(m.value)}, label: ${JSON.stringify(m.label)}, color: ${JSON.stringify(m.color)}, icon: ${JSON.stringify(m.icon)}, mono: ${m.mono} },`);
  }
  out.push(`};`, "");

  // Labels for the other enums.
  const labelMap = (name) => {
    out.push(`export const ${screamingSnake(name)}_LABELS: Record<${name}, string> = {`);
    for (const m of contracts.enums[name].members) out.push(`  ${m.value}: ${JSON.stringify(m.label)},`);
    out.push(`};`, "");
  };
  ["RelationshipType", "Role", "CaseStatus", "JobStatus", "CollectorCost", "KeyService"].forEach(labelMap);

  // Interfaces.
  for (const [name, def] of Object.entries(contracts.interfaces)) {
    out.push(`/** ${def.doc} */`);
    out.push(`export interface ${name} {`);
    for (const f of def.fields) {
      out.push(`  ${f.name}${f.optional ? "?" : ""}: ${tsType(f.type)}${f.optional ? " | null" : ""};`);
    }
    out.push(`}`, "");
  }

  // Palette + constants.
  out.push(`/** ${contracts.palette.doc} */`);
  out.push(`export const PALETTE = ${JSON.stringify(contracts.palette.tokens, null, 2)} as const;`, "");
  out.push(`export const CONSTANTS = ${JSON.stringify(contracts.constants, null, 2)} as const;`, "");

  return out.join("\n");
}

// ---- Python ----------------------------------------------------------------
function buildPy() {
  const out = [BANNER_PY, "from __future__ import annotations", "", "from enum import Enum", "from typing import Any, Dict, List, TypedDict", "", "try:", "    from typing import NotRequired  # py3.11+", "except ImportError:  # pragma: no cover", "    from typing_extensions import NotRequired", "", ""];

  for (const [name, def] of Object.entries(contracts.enums)) {
    out.push(`class ${name}(str, Enum):`);
    out.push(`    """${def.doc}"""`);
    out.push("");
    for (const m of def.members) out.push(`    ${pyMemberName(m.value)} = ${JSON.stringify(m.value)}`);
    out.push("", "");
  }

  // Entity metadata dict.
  out.push(`ENTITY_META: Dict[str, Dict[str, Any]] = {`);
  for (const m of contracts.enums.EntityType.members) {
    out.push(`    ${JSON.stringify(m.value)}: {"value": ${JSON.stringify(m.value)}, "label": ${JSON.stringify(m.label)}, "color": ${JSON.stringify(m.color)}, "icon": ${JSON.stringify(m.icon)}, "mono": ${m.mono ? "True" : "False"}},`);
  }
  out.push(`}`, "");

  out.push(`RELATIONSHIP_LABELS: Dict[str, str] = {`);
  for (const m of contracts.enums.RelationshipType.members) out.push(`    ${JSON.stringify(m.value)}: ${JSON.stringify(m.label)},`);
  out.push(`}`, "");

  // TypedDicts.
  for (const [name, def] of Object.entries(contracts.interfaces)) {
    out.push(`class ${name}(TypedDict):`);
    out.push(`    """${def.doc}"""`);
    out.push("");
    for (const f of def.fields) out.push(`    ${f.name}: ${pyType(f.type, f.optional)}`);
    out.push("", "");
  }

  // Palette + constants.
  out.push(`PALETTE: Dict[str, str] = {`);
  for (const [k, v] of Object.entries(contracts.palette.tokens)) out.push(`    ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  out.push(`}`, "");
  for (const [k, v] of Object.entries(contracts.constants)) out.push(`${k} = ${v}`);
  out.push("");

  return out.join("\n");
}

// ---- write -----------------------------------------------------------------
mkdirSync(resolve(root, "ts"), { recursive: true });
mkdirSync(resolve(root, "python/lighthouse_shared"), { recursive: true });
writeFileSync(resolve(root, "ts/index.ts"), buildTs());
writeFileSync(resolve(root, "python/lighthouse_shared/__init__.py"), buildPy());
console.log("✓ generated ts/index.ts and python/lighthouse_shared/__init__.py from contracts.json");
